from __future__ import annotations
import argparse,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:sys.path.insert(0,str(ROOT))
from benchmark_io import instance_digest,load_instance,save_instance
from pilot_benchmark_suite import PILOT_VERSION,SEEDS,audit_suite,instance_summary,pilot_specs,write_manifests
from synthetic_instance_generator import GENERATOR_VERSION,generate_synthetic_instance

def main():
 p=argparse.ArgumentParser();p.add_argument("--pilot-version",default=PILOT_VERSION);p.add_argument("--output",default="benchmarks/paper_exp_v1_pilot21");p.add_argument("--overwrite",action="store_true");a=p.parse_args()
 if a.pilot_version!=PILOT_VERSION:raise ValueError(f"this builder creates {PILOT_VERSION}, not {a.pilot_version}")
 root=Path(a.output);root.mkdir(parents=True,exist_ok=True);rows=[]
 for iid,(size,spec) in pilot_specs().items():
  instance=generate_synthetic_instance(spec,SEEDS[iid]);relative=f"{size}/{iid}.json";path=root/relative
  if path.exists():
   same=instance_digest(load_instance(path))==instance_digest(instance)
   if same:status="already_exists"
   elif not a.overwrite:raise RuntimeError(f"{iid} has a conflicting digest; use a new suite or --overwrite")
   else:save_instance(instance,path,instance_id=iid);status="overwritten"
  else:save_instance(instance,path,instance_id=iid);status="created"
  row=instance_summary(instance,iid,size,relative,SEEDS[iid]);row["creation_status"]=status;rows.append(row);print(f"{iid}: {status} {row['digest'][:12]}")
 write_manifests(root,rows)
 (root/"README.md").write_text(f"""# {PILOT_VERSION}

Nine deterministic synthetic development benchmarks generated by `{GENERATOR_VERSION}`. They are not public real-port data or final paper results. All sizes use 12 six-hour periods over 72 hours.

Groups encode size, POD, height, and weight class. `ActiveGroupsByShip` is the sparse ship-group index; `G` is its global union. A single-combination POD means at least one active size in that POD has exactly one `(height, weight_class)` combination.

`arrival_overlap_ratio` is the fraction of globally active periods with more than one active new ship. Pairwise overlap is intersection-over-union of two ship windows. Pressure ratios count zero/positive block-period cells; `pressure_cv` is population standard deviation divided by mean and `pressure_p95` is the nearest-rank percentile.

Seeds remain S01-S03=1101-1103, M01-M03=2101-2103, and L01-L03=3101-3103. Pilot1 and Pilot2 remain unchanged. Both candidate and final algorithms remain provisional.
""",encoding="utf-8")
 audit=audit_suite(root);print(f"audit: {audit['status']}");return 0 if audit["status"]=="PASS" else 1
if __name__=="__main__":raise SystemExit(main())
